#!/usr/bin/env bash
# Emit an arduino-cli config for one target and print its path.
#
# WHY GENERATED RATHER THAN CHECKED IN: arduino-cli does NOT expand "~" in a
# config file. A literal "~" in directories.data makes it create a directory
# actually named "~" relative to the working directory -- 3.1 GB of toolchain
# landed inside the repo before this was caught. Absolute paths only, and the
# home directory is not knowable until run time, so the file is generated.
set -uo pipefail
T="${1:?usage: $0 <pod|hub>}"
ROOT="$HOME/.mesquite-arduino/$T"
CFG="$ROOT/arduino-cli.yaml"
mkdir -p "$ROOT"
cat > "$CFG" <<YAML
# GENERATED by tools/arduino_env/mkconfig.sh -- edit that, not this.
#
#   pod  T-Watch 2019   ESP32 core 2.0.17
#        TTGO_TWatch_Library vendors its own TFT_eSPI and lv_lib_png, which use
#        direct GPIO register access and lodepng signatures that IDF 5.x
#        changed. The pod does NOT build on core 3.x.
#   hub  T-Display-S3   ESP32 core 3.x
#        Dongle_Binary.ino targets 3.x/IDF 5.x and needs mathieucarbou's async
#        forks. Other forks fail on mbedtls _ret and pxCurrentTCB.
#
# arduino-cli keeps one core version per data directory, so the two targets
# cannot share one. Neither touches ~/Arduino or ~/.arduino15.
directories:
  data: $ROOT/data
  downloads: $ROOT/staging
  user: $ROOT/user
board_manager:
  additional_urls:
    - https://espressif.github.io/arduino-esp32/package_esp32_index.json
YAML
echo "$CFG"
